#!/usr/bin/env node
// Generate AGENTS.md from skills/offcut/SKILL.md. Never hand-edit AGENTS.md.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skillPath = path.join(root, 'skills', 'offcut', 'SKILL.md');
const outPath = path.join(root, 'AGENTS.md');

const raw = fs.readFileSync(skillPath, 'utf8').replace(/^\uFEFF/, '');
let body = raw;
if (raw.startsWith('---')) {
  const end = raw.indexOf('\n---', 3);
  if (end !== -1) body = raw.slice(end + 4).replace(/^\r?\n/, '');
}

const header = `# AGENTS.md

> Generated from \`skills/offcut/SKILL.md\` by \`scripts/build-agents-md.js\`.
> Do not edit this file by hand. Re-run the script after changing the skill.

`;

const content = header + body.trim() + '\n';
fs.writeFileSync(outPath, content, 'utf8');
process.stdout.write(`Wrote ${path.relative(root, outPath)}\n`);
