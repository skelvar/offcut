#!/usr/bin/env node
// Generate model-facing artifacts from rules/offcut.md. Never hand-edit them.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const kernelPath = path.join(root, 'rules', 'offcut.md');
const agentsPath = path.join(root, 'AGENTS.md');
const skillPath = path.join(root, 'skills', 'offcut', 'SKILL.md');
const cursorPath = path.join(root, 'rules', 'offcut.mdc');

const body = fs.readFileSync(kernelPath, 'utf8').replace(/^\uFEFF/, '').trim();

const header = `# AGENTS.md

> Generated from \`rules/offcut.md\` by \`scripts/build-agents-md.js\`.
> Do not edit this file by hand. Re-run the script after changing the kernel.

`;

const skillHeader = `---
name: offcut
description: >
  Persistent mode that asks what the cheapest working solution is before code
  lands. Activates via lifecycle hooks on supported hosts; usable on demand as
  a skill everywhere else. Use when building, adding features, introducing
  abstractions, or when the user invokes /offcut. Do not use for pure
  explanation, rename-only edits, or formatting.
license: MIT
compatibility: >
  Requires Node.js on the PATH for lifecycle hooks (Claude Code, Codex, Cursor,
  Grok Build). Native persistent instructions are supported on all four hosts;
  the skill remains a compatibility fallback.
metadata:
  version: "0.4.2"
  author: skelvar
---

`;

const outputs = [
  [agentsPath, header + body + '\n'],
  [skillPath, skillHeader + body + '\n'],
  [cursorPath, `---\nalwaysApply: true\n---\n\n${body}\n`],
];

for (const [outPath, content] of outputs) {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, content, 'utf8');
  process.stdout.write(`Wrote ${path.relative(root, outPath)}\n`);
}
